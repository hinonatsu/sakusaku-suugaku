import { readFile, writeFile } from "node:fs/promises";
import { isWebQuestionPlayable } from "../src/question-validation.js";

const args = process.argv.slice(2);
const valueAfter = (flag) => {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : null;
};

const input = valueAfter("--input");
const output = valueAfter("--output") ?? "src/data/questions.js";

if (!input) {
  throw new Error(
    "Usage: node scripts/build-question-bank.mjs --input <questions.csv> [--output src/data/questions.js]"
  );
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (quoted) {
      if (char === '"' && next === '"') {
        cell += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        cell += char;
      }
      continue;
    }

    if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      row.push(cell);
      cell = "";
    } else if (char === "\n") {
      row.push(cell.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      cell = "";
    } else {
      cell += char;
    }
  }

  if (cell || row.length) rows.push([...row, cell.replace(/\r$/, "")]);
  return rows.filter((cells) => cells.some((entry) => entry.trim()));
}

function rowToObject(headers, row) {
  return Object.fromEntries(headers.map((header, index) => [header, row[index] ?? ""]));
}

function splitChoices(choices) {
  return String(choices ?? "")
    .split(/§§|ﾂｧﾂｧ/)
    .map((choice) => choice.trim())
    .filter(Boolean);
}

function parseJson(value) {
  if (!value) return null;
  try {
    return JSON.parse(value);
  } catch {
    return null;
  }
}

function hasUnusableWarning(errorTags) {
  return /(条件不足|読取不能|前ページ|NEEDS_|図.*必須|DIAGRAM_NEEDED)/i.test(errorTags ?? "");
}

function toNumber(value, fallback = 2) {
  const number = Number(value);
  return Number.isFinite(number) ? number : fallback;
}

const knownExplanationIssues = new Set([
  "textbook-sec1-practice-l002-q005",
  "textbook-sec1-practice-l002-q006"
]);

function toQuestion(row) {
  const interaction = parseJson(row.interactionData);
  const choices = splitChoices(row.choices);
  const interactionChoices = Array.isArray(interaction?.choices)
    ? interaction.choices.map((choice) => String(choice.label ?? choice.value ?? "").trim()).filter(Boolean)
    : [];
  const effectiveChoices = choices.length ? choices : interactionChoices;
  const requiresVisual = Boolean(row.visualAssetId);
  const answer = String(row.answer ?? "").trim();
  const type = String(row.questionType ?? "").trim();
  const basicFieldsPresent = Boolean(row.questionText?.trim() && answer && row.explanation?.trim());

  const question = {
    id: row.questionId,
    grade: row.grade,
    unit: row.unitId,
    unitName: row.unitNameJa,
    lesson: row.lessonId,
    skill: row.skillTitle,
    type,
    activityType: row.activityType,
    question: row.questionText.trim(),
    answer,
    answerRequirement: row.answerRequirement || "value_equivalent",
    explanation: row.explanation.trim(),
    choices: effectiveChoices,
    interaction,
    difficulty: toNumber(row.difficulty),
    recommendedSeconds: toNumber(row.recommendedSeconds, 45),
    visualAssetId: row.visualAssetId || null,
    errorTags: row.errorTags || "",
    chainId: row.chainId || row.questionId,
    stepIndex: Number(row.stepIndex || 1),
    stepCount: Number(row.stepCount || 1),
    sourceProblemId: row.sourceProblemId || "",
    eligible: false
  };

  question.eligible =
    basicFieldsPresent &&
    !requiresVisual &&
    !hasUnusableWarning(row.errorTags) &&
    !knownExplanationIssues.has(row.questionId) &&
    isWebQuestionPlayable(question);

  return question;
}

const raw = await readFile(input, "utf8");
const rows = parseCsv(raw);
const headers = rows[0];
const questions = rows.slice(1).map((row) => toQuestion(rowToObject(headers, row)));
const eligibleCount = questions.filter((question) => question.eligible).length;

const sourceLabel = input.replace(/\\/g, "/").split("/").pop();
const generated = `// Generated by scripts/build-question-bank.mjs from ${sourceLabel}.\n// Do not edit by hand; regenerate from the current question CSV.\n\nexport const questionBank = ${JSON.stringify(
  questions
)};\n\nexport const questionBankMeta = { total: ${questions.length}, eligible: ${eligibleCount} };\n\nexport function createQuestionPool() {\n  return questionBank.map((question) => ({\n    ...question,\n    choices: [...question.choices],\n    interaction: question.interaction ? structuredClone(question.interaction) : null\n  }));\n}\n`;

await writeFile(output, generated, "utf8");
console.log(`Generated ${questions.length} questions (${eligibleCount} eligible for the web trial).`);
