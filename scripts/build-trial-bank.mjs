import { writeFile } from "node:fs/promises";

import { applyQuestionOverride } from "../src/data/question-overrides.js";
import { questionBank } from "../src/data/questions.js";
import { isWebQuestionPlayable, rendererType } from "../src/question-validation.js";

const OUTPUT = "src/data/trial-questions.js";
const GRADES = ["中1", "中2", "中3"];
const QUOTAS = { choice: 70, input: 70, table: 10, graph: 10, steps: 10 };

function pickAcrossUnits(questions, limit) {
  const groups = new Map();
  for (const question of questions) {
    const group = groups.get(question.unit) ?? [];
    group.push(question);
    groups.set(question.unit, group);
  }
  const unitIds = [...groups.keys()].sort();
  const selected = [];
  let index = 0;
  while (selected.length < limit && unitIds.length) {
    const unitIndex = index % unitIds.length;
    const unitId = unitIds[unitIndex];
    const group = groups.get(unitId);
    selected.push(group.shift());
    if (group.length === 0) unitIds.splice(unitIndex, 1);
    else index += 1;
  }
  return selected;
}

const corrected = questionBank
  .map((question) => applyQuestionOverride(structuredClone(question)))
  .filter((question) => question.eligible && question.difficulty <= 2 && isWebQuestionPlayable(question));

const selected = [];
for (const grade of GRADES) {
  const gradeQuestions = corrected.filter((question) => question.grade === grade);
  for (const [kind, quota] of Object.entries(QUOTAS)) {
    selected.push(
      ...pickAcrossUnits(
        gradeQuestions.filter((question) => rendererType(question) === kind),
        quota
      )
    );
  }
}

const unique = [...new Map(selected.map((question) => [question.id, question])).values()];
const gradeCounts = Object.fromEntries(
  GRADES.map((grade) => [grade, unique.filter((question) => question.grade === grade).length])
);
const source = `// Generated by scripts/build-trial-bank.mjs. Do not edit by hand.\n\n` +
  `export const trialQuestionBank = ${JSON.stringify(unique)};\n\n` +
  `export const trialQuestionBankMeta = ${JSON.stringify({ total: unique.length, gradeCounts })};\n`;

await writeFile(OUTPUT, source, "utf8");
console.log(`Generated ${unique.length} validated trial questions: ${JSON.stringify(gradeCounts)}`);
